"""Olympus data and emulator access: paths, measurements, and the BNN forward pass.

Deliberately **numpy-only** -- no torch, no `eval.benchmarks.base`, no scipy at
import time. Two reasons:

* `eval/scripts/verify_olympus_emulator.py` runs in the throwaway TensorFlow venv
  and imports *this* module to compare against TFP's own
  `DenseLocalReparameterization`. Verifying a copy of the forward pass would prove
  nothing about the one the sweep runs, so the sweep and the verifier must share
  this code.
* Nothing here should be able to pull TensorFlow or a MatFormBench extension into
  a worker process.

## The emulator

Olympus ships a trained `BayesNeuralNet` per dataset. `scripts/extract_olympus_emulator.py`
lifts its weights and scaler statistics into `eval/data/olympus/emulator_<ds>.{npz,json}`;
this module reimplements the forward pass over those arrays. The architecture is
read from the artifacts rather than assumed -- `photo_pce10` has four layers and
`oer_plate_3496` three, and both use `out_act="relu"` where the class default is
linear.

Each layer is a `tfp.layers.DenseLocalReparameterization`. The kernel is random
with a mean-field Gaussian posterior; the bias is *singular* (a point mass at
`loc`), which is TFP's default. Local reparameterization means the layer never
samples a weight matrix -- it samples the pre-activation directly:

    mean = h @ kernel_loc + bias
    var  = (h ** 2) @ kernel_scale ** 2
    out  = activation(mean + sqrt(var) * eps),    eps ~ N(0, 1)

so `mean_pass=True` (no `eps`) is the noiseless response and a draw is a noisy
one. That split is what lets `truth` and `observe` differ without inventing a
noise model: the noise is the emulator's own epistemic uncertainty.

`kernel_scale = softplus(untransformed_scale) + eps32` reproduces TFP's
`default_loc_scale_fn` exactly, including the float32 epsilon it adds.

Verified against TFP at
`max|TFP_noiseless - numpy_mean_pass| <= 1.8e-6`, which is float32 accumulation
round-off over 48-wide matmuls, with the sampled distribution's gap to TFP's
shrinking as 1/sqrt(K). See `verify_olympus_emulator.py`.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[3]

#: Repo-relative location of the shallow clone. Overridable for CI.
OLYMPUS_ROOT = Path(
    os.environ.get("OLYMPUS_ROOT", REPO / "eval" / "external" / "olympus")
)

#: Extracted emulator artifacts. Committed? No -- `eval/data/` is gitignored, so
#: they are regenerated by the extraction script, which is committed.
ARTIFACT_DIR = Path(
    os.environ.get("OLYMPUS_ARTIFACTS", REPO / "eval" / "data" / "olympus")
)

SUITE = "olympus"

#: Slack when testing hull membership. Well above float64 round-off on a facet and
#: far below any composition difference that could matter -- 1e-9 of a unit
#: mixture fraction. See `hull_membership` for why an exact test fails.
HULL_TOL = 1e-9


def dataset_dir(dataset: str) -> Path:
    return OLYMPUS_ROOT / "src" / "olympus" / "datasets" / f"dataset_{dataset}"


def load_config(dataset: str) -> dict:
    with open(dataset_dir(dataset) / "config.json", encoding="utf-8") as handle:
        return json.load(handle)


def load_measurements(dataset: str) -> tuple[np.ndarray, np.ndarray]:
    """The shipped measurement table: `(X, y)` with `y` 1-D.

    `data.csv` has **no header row** -- the first line is data. Reading it with a
    header silently drops one measurement (1040 -> 1039) and shifts nothing else,
    so the loss is easy to miss.
    """
    raw = np.loadtxt(dataset_dir(dataset) / "data.csv", delimiter=",")
    config = load_config(dataset)
    n_x = len(config["parameters"])
    n_y = len(config["measurements"])
    if raw.shape[1] != n_x + n_y:
        raise ValueError(
            f"{dataset}: data.csv has {raw.shape[1]} columns, config declares "
            f"{n_x} parameters + {n_y} measurements"
        )
    return raw[:, :n_x], raw[:, n_x]


# -- the extracted emulator --------------------------------------------------

@dataclass(frozen=True)
class Emulator:
    """Weights, scalers and architecture of one extracted Olympus emulator."""

    dataset: str
    n_layers: int
    kernel_loc: tuple[np.ndarray, ...]
    kernel_scale: tuple[np.ndarray, ...]
    bias_loc: tuple[np.ndarray, ...]
    hidden_act: str
    out_act: str
    feature_transform: str
    target_transform: str
    #: Statistics for whichever transform is declared, keyed as in `TRANSFORMS`.
    x_stats: dict
    y_stats: dict
    meta: dict

    @property
    def dim(self) -> int:
        return int(self.kernel_loc[0].shape[0])


#: Activations, transcribed from Olympus's own `WrapperTensorflowModel.act_funcs`.
#: `leaky_relu`'s slope of 0.2 is theirs, not a default.
ACTIVATIONS: dict = {
    "linear": lambda y: y,
    "leaky_relu": lambda y: np.maximum(y, 0.2 * y),
    "relu": lambda y: np.maximum(y, 0.0),
    "sigmoid": lambda y: 1.0 / (1.0 + np.exp(-y)),
    "softplus": lambda y: np.log1p(np.exp(-np.abs(y))) + np.maximum(y, 0.0),
    "softsign": lambda y: y / (1.0 + np.abs(y)),
}

#: Forward and inverse of each `DataTransformer` transformation we encounter,
#: transcribed from `olympus/utils/data_transformer.py`. Features go forward on
#: the way in, targets come back on the way out. Note `standardize` divides by
#: `_stable_stddev` while `mean` divides by `_mean` -- different statistics, and
#: the emulators genuinely differ: photo_pce10 uses standardize -> mean, while
#: colors_bob uses identity -> identity.
TRANSFORMS: dict = {
    "identity": (lambda v, st: v, lambda v, st: v),
    "standardize": (
        lambda v, st: (v - st["mean"]) / st["stddev"],
        lambda v, st: v * st["stddev"] + st["mean"],
    ),
    "normalize": (
        lambda v, st: (v - st["min"]) / (st["max"] - st["min"]),
        lambda v, st: v * (st["max"] - st["min"]) + st["min"],
    ),
    "mean": (
        lambda v, st: v / st["mean"],
        lambda v, st: v * st["mean"],
    ),
}


def _softplus(x: np.ndarray) -> np.ndarray:
    """Numerically stable ``log(1 + exp(x))``."""
    return np.log1p(np.exp(-np.abs(x))) + np.maximum(x, 0.0)


def load_emulator(dataset: str) -> Emulator:
    npz_path = ARTIFACT_DIR / f"emulator_{dataset}.npz"
    json_path = ARTIFACT_DIR / f"emulator_{dataset}.json"
    if not npz_path.exists():
        raise FileNotFoundError(
            f"{npz_path} is missing. Regenerate it with\n"
            f"    .venv-olympus/bin/python eval/scripts/extract_olympus_emulator.py "
            f"--datasets {dataset}"
        )
    meta = json.loads(json_path.read_text(encoding="utf-8"))

    for key in ("hidden_act", "out_act"):
        if meta[key] not in ACTIVATIONS:
            raise ValueError(
                f"{dataset}: unsupported {key} {meta[key]!r}; known: {sorted(ACTIVATIONS)}"
            )
    for key in ("feature_transform", "target_transform"):
        chain = meta[key]
        # Olympus allows a chain; every emulator we use declares exactly one.
        if len(chain) != 1 or chain[0] not in TRANSFORMS:
            raise ValueError(
                f"{dataset}: unsupported {key} {chain}; known: {sorted(TRANSFORMS)}"
            )

    with np.load(npz_path) as data:
        n = int(meta["n_layers"])
        eps = float(meta["softplus_eps"])
        return Emulator(
            dataset=dataset,
            n_layers=n,
            kernel_loc=tuple(data[f"w{i}_loc"] for i in range(n)),
            # softplus(untransformed) + eps32 is TFP's default_loc_scale_fn.
            kernel_scale=tuple(
                _softplus(data[f"w{i}_untransformed_scale"]) + eps for i in range(n)
            ),
            bias_loc=tuple(data[f"b{i}_loc"] for i in range(n)),
            hidden_act=meta["hidden_act"],
            out_act=meta["out_act"],
            feature_transform=meta["feature_transform"][0],
            target_transform=meta["target_transform"][0],
            x_stats={
                "mean": data["x_mean"], "stddev": data["x_stddev"],
                "min": data["x_min"], "max": data["x_max"],
            },
            y_stats={
                "mean": data["y_mean"], "stddev": data["y_stddev"],
                "min": data["y_min"], "max": data["y_max"],
            },
            meta=meta,
        )


def forward(
    emu: Emulator,
    X: np.ndarray,
    rng: np.random.Generator | None = None,
    *,
    mean_pass: bool = False,
) -> np.ndarray:
    """Response for raw designs `X`, shape `(n, 1)`.

    `mean_pass=True` is the noiseless response (`truth`); otherwise one local
    reparameterization draw per row (`observe`) and `rng` is required.

    Scaling is part of the model, not of the caller: features go through the
    emulator's own feature transform on the way in and the target comes back
    through its target transform on the way out, matching `Emulator.run`.
    """
    if not mean_pass and rng is None:
        raise ValueError("a sampled forward pass needs an rng")

    forward_x, _ = TRANSFORMS[emu.feature_transform]
    _, back_y = TRANSFORMS[emu.target_transform]
    hidden = ACTIVATIONS[emu.hidden_act]
    out = ACTIVATIONS[emu.out_act]

    h = forward_x(np.atleast_2d(np.asarray(X, dtype=float)), emu.x_stats)
    last = emu.n_layers - 1
    for i in range(emu.n_layers):
        mean = h @ emu.kernel_loc[i] + emu.bias_loc[i]
        if mean_pass:
            h = mean
        else:
            var = (h ** 2) @ (emu.kernel_scale[i] ** 2)
            h = mean + np.sqrt(np.maximum(var, 0.0)) * rng.standard_normal(mean.shape)
        h = hidden(h) if i < last else out(h)
    return back_y(h, emu.y_stats)


# -- input feasibility on the simplex ---------------------------------------

def interior_support(dataset: str) -> float:
    """Share of measurements with *every* mixture component non-zero.

    The property a convex-hull feasibility test cannot see, and the reason
    `oer_plate_3496` was rejected as a task after being selected.

    All four `oer_plate` datasets mix at most 4 of their 6 components: not one of
    ~2,120 measurements has 5 or 6 non-zero loadings, so this returns 0.0. Yet
    their hull test reports 100% feasible, because the hull of those faces is the
    entire simplex once all six vertices are present. Our initial design and
    calibration reference measure are uniform Dirichlet draws, which almost surely
    have every component non-zero -- so every design evaluated would sit in a
    stratum the emulator never trained on, while both the hull test and the
    nearest-neighbour distance (median 0.098 against a 0.141 data grid, because
    the nearest measurement is always on a face) look healthy.

    Measured: colors_bob 100%, photo_pce10 / photo_wf3 80.7%, thin_film 56.4%,
    every oer_plate 0.0%.
    """
    X, _ = load_measurements(dataset)
    return float(((X > 0.0).sum(axis=1) >= X.shape[1]).mean())


#: Minimum `interior_support` for an emulator task to be usable under a uniform
#: reference measure. Set between thin_film's 56.4% and oer_plate's 0%: the point
#: is to exclude designs-on-faces-only datasets, not to demand saturation.
#: `test_olympus.py` enforces it on every selected task.
SUPPORT_FLOOR = 0.5


def activation_floor_rate(dataset: str) -> float:
    """Share of an emulator's own training designs it predicts at the activation floor.

    The third way an Olympus emulator turns out to be unusable, after
    "declares a simplex it does not have" (`colors_bob`) and "simplex with no
    interior" (`oer_plate`). It is the sharpest of the three because it needs no
    reference measure: the emulator is asked about the very points it was fit to.

    `p3ht` fails it at **41.6%** -- it predicts exactly 0 for four in ten of its own
    training designs, while not one of its 178 measured conductivities is 0. Its
    output activation is `relu`, so any negative pre-activation is flattened, and
    that is also why its published R2 is the weakest of the candidates (0.69). Over
    a uniform reference measure the damage compounds: 76.6% of hull-interior draws
    come back at exactly 0, so the response distribution collapses to a point mass
    and a synthesized quantile threshold degenerates -- p3ht's window calibrated to
    the empty interval [0, 0].

    Related and worth reporting even when it passes: the median distance from a
    uniform hull-interior draw to the nearest measurement, over the median spacing
    *between* measurements. pce10 and wf3 sit at 0.80, p3ht at 9.80 -- its 178
    points occupy a thin region whose convex hull encloses a far larger volume, and
    no hull test can see that. It is a diagnostic rather than a gate because
    clustered or duplicated designs deflate the denominator (thin_film reads 3.31
    for that reason while being sound on every other measure).
    """
    X, _ = load_measurements(dataset)
    emu = load_emulator(dataset)
    if emu.out_act != "relu":
        return 0.0
    return float(np.mean(forward(emu, X, mean_pass=True).ravel() <= 0.0))


#: How much of its own training set an emulator may flatten onto the activation
#: floor. Set between wf3's 0.1% and p3ht's 41.6%.
FLOOR_RATE_CEILING = 0.05


def hull_membership(dataset: str, X: np.ndarray, tol: float = HULL_TOL) -> np.ndarray:
    """Whether each design lies in the convex hull of the measured compositions.

    A mixture task's simplex need not be covered by its measurements, and the
    emulator has no support outside them. Designs outside the hull are reported
    input-infeasible rather than silently extrapolated -- the same separation of
    input feasibility from outcome validity that the MatFormBench protocol keeps.

    Implemented with the hull's facet inequalities (`A x + b <= 0`) rather than a
    Delaunay triangulation, for two measured reasons. Delaunay on
    `oer_plate_3496` (2,121 points, 5-D) takes 206 s to build against
    milliseconds here, and it reported 22 of `photo_pce10`'s own 1,040
    measurements as outside their own hull -- points sitting exactly on a face,
    lost to round-off. Faces are not an edge case: a blend that omits an
    ingredient lies on one, and an acquisition optimizer pushes toward exactly
    those boundaries. Hence an explicit tolerance instead of an exact predicate.

    The hull is taken in the simplex's own `dim - 1` coordinates. On a simplex the
    points are co-planar, so the full-dimensional problem is degenerate.

    What this measures per task, on 200k uniform draws:

        photo_pce10       8 facets, 99.89% of the simplex inside -- a real
                          constraint, and 0.11% of designs are input-infeasible
        oer_plate_3496    6 facets, i.e. the hull *is* the simplex: every design
                          is input-feasible and this task exercises no input
                          feasibility at all. Reported, not glossed.
    """
    A, b = _hull_equations(dataset)
    Y = np.atleast_2d(np.asarray(X, dtype=float))[:, :-1]
    return (Y @ A.T + b <= tol).all(axis=1)


def _hull_equations(dataset: str) -> tuple[np.ndarray, np.ndarray]:
    cached = _HULL_CACHE.get(dataset)
    if cached is None:
        from scipy.spatial import ConvexHull  # noqa: PLC0415  -- keeps import numpy-only

        pool, _ = load_measurements(dataset)
        hull = ConvexHull(pool[:, :-1])
        cached = (hull.equations[:, :-1].copy(), hull.equations[:, -1].copy())
        _HULL_CACHE[dataset] = cached
    return cached


#: Facet equations per dataset per process. Building them is milliseconds, so
#: there is nothing to persist -- this only avoids repeating it per batch.
_HULL_CACHE: dict[str, tuple[np.ndarray, np.ndarray]] = {}
